esp_lcd_touch_handle_t tp = NULL;

void reflect_display(void) {
  bsp_display_start();
  bsp_display_backlight_on();

  bsp_display_lock(0);
  auto scr = lv_screen_active();

  lv_obj_set_style_bg_color(scr, lv_color_black(), LV_PART_MAIN);
  lv_obj_set_style_bg_opa(scr, LV_OPA_COVER, LV_PART_MAIN);

  status_label = lv_label_create(scr);
  lv_label_set_text(status_label, "Device is ");
  lv_label_set_text(status_label, "Device is ready and will connect\nautomatically if everything is ok.\n\nIf this message does not change\nafter a few moments, you may want\nto check under the hood.");
  lv_obj_set_style_text_color(status_label, lv_color_hex(0xFFFFFF), LV_PART_MAIN);
  lv_obj_set_style_text_align(status_label, LV_TEXT_ALIGN_CENTER, LV_PART_MAIN);
  lv_obj_center(status_label);

  mic_img = lv_img_create(scr);
  lv_img_set_src(mic_img, &mic);

  int inset = 4;
  lv_obj_align(mic_img, LV_ALIGN_TOP_RIGHT, -inset, inset);
  lv_obj_move_foreground(mic_img);

  lv_obj_set_style_img_recolor_opa(mic_img, LV_OPA_COVER, LV_PART_MAIN);
  reflect_set_mic_color(false);

  ESP_ERROR_CHECK(bsp_touch_new(NULL, &tp));

  bsp_display_unlock();
}

bool reflect_display_pressed(void) {
  uint16_t touch_x[1];
  uint16_t touch_y[1];
  uint16_t touch_strength[1];
  uint8_t touch_cnt = 0;

  esp_lcd_touch_read_data(tp);
  return esp_lcd_touch_get_coordinates(tp, touch_x, touch_y, touch_strength,
                                       &touch_cnt, 1);
}

void reflect_set_spin(bool s) { 
  if (s) {
    bsp_display_lock(0);
    lv_label_set_text(status_label, "Connected successfully.\n\nYou should be able to speak\nand hear back and see lights change.\n\nTo stop, power down or restart\nthis device.");
    lv_obj_center(status_label);
    bsp_display_unlock();
  }
}

void reflect_set_mic_color(bool muted) {
  bsp_display_lock(0);

  if (muted) {
    lv_obj_set_style_img_recolor(mic_img, lv_color_hex(0xFF0000), LV_PART_MAIN);
  } else {
    lv_obj_set_style_img_recolor(mic_img, lv_color_hex(0xFFFFFF), LV_PART_MAIN);
  }

  bsp_display_unlock();
}
